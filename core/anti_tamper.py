"""Target-based anti-tamper integrity verification.

Policy (per product decision)
-----------------------------
* **DEV mode** (``LICENSING_ENABLED`` not truthy): mismatches are logged as
  warnings only. Local development and runtime self-improvement are never
  interrupted.
* **RELEASE mode** (``LICENSING_ENABLED=true``): the app refuses to start if one
  of the *guarded* files has been modified from its recorded hash. Guarded files
  are the ones that must never legitimately change at runtime:
  ``core/license_guard.py`` and ``core/brand.py``.
* ``tools/`` and dynamic skill modules are **never** guarded - they are designed
  to be regenerated by SkillForge/self_improvement.

The manifest is ``core/integrity_manifest.json``. It is written by
``build_release.py --sign-integrity`` and shipped inside the commercial ZIP. A
missing manifest means "not enforced" so a fresh checkout/developer run cannot
be bricked by a stale hash.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

__all__ = [
    "GUARDED_FILES",
    "manifest_path",
    "file_digest",
    "compute_manifest",
    "write_manifest",
    "load_manifest",
    "find_violations",
    "enforce",
    "IntegrityError",
]

_ROOT = Path(__file__).resolve().parent.parent

# Files that must not change after a signed release build.
GUARDED_FILES: tuple[str, ...] = (
    "core/license_guard.py",
    "core/brand.py",
)

_MANIFEST_NAME = "integrity_manifest.json"


class IntegrityError(RuntimeError):
    """Raised in release mode when a guarded file fails its checksum."""


def manifest_path() -> Path:
    return Path(__file__).resolve().parent / _MANIFEST_NAME


def file_digest(rel_path: str) -> str | None:
    target = _ROOT / rel_path
    if not target.is_file():
        return None
    try:
        data = target.read_bytes()
    except Exception:
        return None
    return hashlib.sha256(data).hexdigest()


def compute_manifest() -> dict[str, str]:
    return {rel: digest for rel in GUARDED_FILES if (digest := file_digest(rel))}


def write_manifest() -> Path:
    path = manifest_path()
    try:
        path.write_text(
            json.dumps({"version": 1, "files": compute_manifest()}, indent=2),
            encoding="utf-8",
        )
    except Exception:
        pass
    return path


def load_manifest() -> dict[str, str] | None:
    path = manifest_path()
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None
    files = data.get("files") if isinstance(data, dict) else None
    if isinstance(files, dict):
        return {str(k): str(v) for k, v in files.items()}
    return None


def find_violations() -> list[str]:
    """Return a list of human-readable integrity violations (empty == intact)."""
    manifest = load_manifest()
    if manifest is None:
        return []
    violations: list[str] = []
    for rel, expected in manifest.items():
        actual = file_digest(rel)
        if actual is None:
            violations.append(f"{rel}: missing")
        elif actual != expected:
            violations.append(f"{rel}: modified (checksum mismatch)")
    return violations


def enforce(*, release: bool) -> list[str]:
    """Evaluate integrity for the current mode.

    Returns the list of violations. In release mode a non-empty list raises
    :class:`IntegrityError`; in dev mode it only returns them for logging.
    """
    violations = find_violations()
    if violations and release:
        raise IntegrityError(
            "Integrity check failed for protected files: " + "; ".join(violations)
        )
    return violations
